// Generates src/app/styles/colors.css from src/utils/constants/colors.js.
// Run with `npm run colors` (also runs automatically before `dev` and `build`).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  COLOR_TOKENS,
  TAILWIND_COLOR_PREFIXES,
} from "../src/utils/constants/colors.js";

const outFile = fileURLToPath(
  new URL("../src/app/styles/colors.css", import.meta.url),
);

const tokens = Object.values(COLOR_TOKENS);

const themeVars = tokens
  .map(({ tw, value }) => `  --color-${tw}: ${value.toLowerCase()};`)
  .join("\n");

const safelist = tokens
  .flatMap(({ tw }) => TAILWIND_COLOR_PREFIXES.map((p) => `${p}${tw}`))
  .join(" ");

const css = `/* ⚠️ AUTO-GENERATED by scripts/generate-colors.mjs — DO NOT EDIT. */
/* Edit COLOR_TOKENS in src/utils/constants/colors.js, then run \`npm run colors\`. */

@theme {
${themeVars}
}

/* Classes built dynamically in colors.js maps (Tailwind can't detect them). */
@source inline("${safelist}");
`;

writeFileSync(outFile, css);
console.log(`✓ colors.css generated (${tokens.length} colors)`);
